import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const app=path.join(root,'desktop/apps/stage-tamagotchi');
const require=createRequire(path.join(app,'package.json'));
const cli=path.join(path.dirname(require.resolve('electron-vite')),'cli.js');
const args=[cli,process.argv.includes('--dev')?'dev':'build','--config','electron-integration.config.ts'];
const result=spawnSync(process.execPath,args,{cwd:app,stdio:'inherit',env:process.env});
if(result.error) throw result.error;
process.exitCode=result.status??1;
